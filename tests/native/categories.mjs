import { expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { randomUUID, createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

export async function verifyCategories({ main, preview, cli, invoke, osWindows, mainHandle, recordId, contact, repo, runDirectory, focusPreview, check }) {
  const row = (dialog, id) => dialog.locator(`[data-category-id="${id}"]`);
  const nav = name => main.locator('.sidebar .nav-item[title]').filter({ has: main.locator('span', { hasText: new RegExp(`^${name}$`) }) });
  const hash = bytes => createHash('sha256').update(bytes).digest('hex');
  async function manager(locale = 'en') {
    await main.getByRole('button', { name: locale === 'en' ? 'Manage collections' : '管理分类', exact: true }).click();
    const dialog = main.getByRole('dialog', { name: locale === 'en' ? 'Collections' : '分类', exact: true });
    await expect(dialog).toBeVisible();
    return dialog;
  }
  async function save(dialog, locale = 'en') {
    await dialog.getByRole('button', { name: locale === 'en' ? 'Save changes' : '保存更改', exact: true }).click();
    await expect(dialog).toBeHidden();
  }
  async function resize(width, height) {
    const scale = await main.evaluate(() => devicePixelRatio);
    osWindows('resize', mainHandle, { width: Math.round(width * scale), height: Math.round(height * scale) });
    const state = osWindows().find(window => window.handle === mainHandle);
    await expect.poll(() => main.evaluate(({ width, height }) => Math.max(Math.abs(innerWidth * devicePixelRatio - width), Math.abs(innerHeight * devicePixelRatio - height)), { width: state.clientWidth, height: state.clientHeight })).toBeLessThanOrEqual(2);
  }
  const original = await cli('get', ['--id', recordId]);
  const originalHashes = await Promise.all(original.attachments.map(async attachment => hash(await readFile(attachment.absolutePath))));
  const initial = await cli('categories');
  assert.equal(initial.categories.length, 9);
  assert.equal(initial.revision, 'builtin-v1');
  let dialog = await manager();
  await expect(dialog.locator('[data-category-id]')).toHaveCount(9);
  await row(dialog, 'contacts').getByLabel('English name', { exact: true }).fill('People archive');
  await row(dialog, 'contacts').getByLabel('Chinese name', { exact: true }).fill('人物档案');
  await row(dialog, 'contacts').getByRole('button', { name: 'Choose icon', exact: true }).click();
  await dialog.getByRole('button', { name: 'Book', exact: true }).click();
  await row(dialog, 'education').getByRole('button', { name: 'Move up', exact: true }).click();
  await dialog.getByRole('button', { name: 'New collection', exact: true }).click();
  const added = dialog.locator('[data-category-id]').last();
  const customId = await added.getAttribute('data-category-id');
  assert.match(customId, /^collection-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
  await added.getByLabel('English name', { exact: true }).fill('Trips');
  await added.getByLabel('Chinese name', { exact: true }).fill('行程');
  await added.getByRole('button', { name: 'Choose icon', exact: true }).click();
  await dialog.getByRole('button', { name: 'Travel', exact: true }).click();
  await row(dialog, customId).getByRole('button', { name: 'Move up', exact: true }).click();
  await row(dialog, customId).locator('.category-drag').press('ArrowUp');
  await expect(dialog.locator('[data-category-id]').nth(7)).toHaveAttribute('data-category-id', customId);
  await save(dialog);
  const catalog = await cli('categories');
  const order = ['education', 'identity', 'experience', 'research', 'awards', 'skills', 'contacts', customId, 'documents', 'custom'];
  assert.deepEqual(catalog.categories.map(category => category.id), order);
  assert.notEqual(catalog.revision, 'builtin-v1');
  assert.deepEqual(catalog.categories.find(category => category.id === 'contacts'), { id: 'contacts', nameEn: 'People archive', nameZh: '人物档案', icon: 'book-open' });
  assert.deepEqual(catalog.categories.find(category => category.id === customId), { id: customId, nameEn: 'Trips', nameZh: '行程', icon: 'plane' });
  const after = await cli('get', ['--id', recordId]);
  assert.deepEqual(after.record, original.record);
  assert.deepEqual(after.attachments, original.attachments);
  assert.deepEqual(await Promise.all(after.attachments.map(async attachment => hash(await readFile(attachment.absolutePath)))), originalHashes);
  await expect(nav('People archive').locator('svg.lucide-book-open')).toHaveCount(1);
  await expect(nav('Trips').locator('svg.lucide-plane')).toHaveCount(1);
  await expect(main.locator('.detail-category')).toHaveText('People archive');
  await main.getByRole('button', { name: 'Edit', exact: true }).click();
  const existing = main.getByRole('dialog', { name: 'Edit', exact: true });
  await expect(existing.getByRole('combobox', { name: 'Collection', exact: true })).toHaveValue('contacts');
  await expect(existing.getByRole('combobox', { name: 'Collection', exact: true }).locator('option:checked')).toHaveText('People archive');
  await existing.getByRole('button', { name: 'Cancel', exact: true }).click();
  const schema = await cli('schema');
  assert.deepEqual(schema.categories, catalog.categories);
  assert.equal(schema.categoriesRevision, catalog.revision);
  assert.deepEqual(schema.record.properties.category.enum, order);
  await assert.rejects(() => invoke(preview, 'save_categories', { categories: catalog.categories, expectedRevision: catalog.revision }), /INVALID_CATEGORIES/);
  assert.equal((await cli('categories')).revision, catalog.revision);
  check('Real UI collection names, icons and order persist; CLI discovery matches; files stay unchanged and child catalog writes reject');

  await nav('Trips').click();
  await expect(main.locator('.record-card')).toHaveCount(0);
  await main.getByRole('button', { name: 'New record', exact: true }).click();
  const editor = main.getByRole('dialog', { name: 'New record', exact: true });
  await expect(editor.getByRole('combobox', { name: 'Collection', exact: true })).toHaveValue(customId);
  await editor.getByLabel('Title', { exact: true }).fill('Synthetic UI itinerary');
  await editor.getByRole('combobox', { name: 'Collection', exact: true }).selectOption(customId);
  await editor.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(editor).toBeHidden();
  await expect(main.locator('.detail-category')).toHaveText('Trips');
  const listing = await cli('list');
  assert.equal(listing.records.find(record => record.title === 'Synthetic UI itinerary').category, customId);
  assert.deepEqual(listing.categories, catalog.categories);
  const custom = { id: randomUUID(), category: customId, title: 'Synthetic CLI itinerary', fields: [{ id: 'destination', label: 'Destination', labelZh: '目的地', value: 'Synthetic example', kind: 'text', sensitive: false }] };
  await cli('validate', [], custom);
  await cli('create', [], custom);
  const imported = (await cli('attach', ['--record-id', custom.id], [path.join(repo, 'tests/fixtures/portrait.jpg')])).attachments[0];
  assert(imported.fileName.startsWith(`${customId}_`));
  assert.equal((await cli('validate', [], { ...custom, category: `collection-${randomUUID()}` }, 2)).code, 'UNKNOWN_CATEGORY');
  const customSaved = await cli('get', ['--id', custom.id]);
  assert.equal(customSaved.record.category, customId);
  assert.deepEqual(customSaved.categories, catalog.categories);
  await main.reload();
  await expect(nav('Trips')).toBeVisible();
  assert.deepEqual(await main.locator('.sidebar .nav-item[title] > span').allTextContents(), catalog.categories.map(category => category.nameEn));
  await nav('Trips').click();
  await expect(main.locator('.record-card')).toHaveCount(2);
  await main.locator('.record-card').filter({ hasText: 'Synthetic UI itinerary' }).click();
  await main.getByRole('button', { name: 'Edit', exact: true }).click();
  const reopened = main.getByRole('dialog', { name: 'Edit', exact: true });
  await expect(reopened.getByRole('combobox', { name: 'Collection', exact: true })).toHaveValue(customId);
  await reopened.getByRole('button', { name: 'Cancel', exact: true }).click();
  const snapshot = await invoke(main, 'load_snapshot');
  assert.deepEqual(snapshot.categories, catalog.categories);
  assert.equal(snapshot.records.find(record => record.id === recordId).category, 'contacts');
  check('UI and CLI custom records and attachments retain membership after reload; unregistered IDs reject');

  for (const locale of ['en', 'zh']) {
    if (locale === 'zh') await main.locator('.locale-toggle').click();
    const labels = locale === 'en'
      ? { english: 'English name', chinese: 'Chinese name', save: 'Save changes', cancel: 'Cancel', discard: 'Discard', conflict: /Collections changed elsewhere/ }
      : { english: '英文名称', chinese: '中文名称', save: '保存更改', cancel: '取消', discard: '放弃更改', conflict: /分类已在其他地方更新/ };
    dialog = await manager(locale);
    const proposal = `Pending people ${locale}`;
    await row(dialog, 'contacts').getByLabel(labels.english, { exact: true }).fill(proposal);
    const before = await cli('categories');
    const external = before.categories.map(category => category.id === 'contacts' ? { ...category, nameEn: `External people ${locale}`, nameZh: `外部人物${locale}` } : category);
    const changed = await invoke(main, 'save_categories', { categories: external, expectedRevision: before.revision });
    await dialog.getByRole('button', { name: labels.save, exact: true }).click();
    await expect(dialog.getByRole('alert')).toContainText(labels.conflict);
    await expect(dialog.getByRole('alert')).not.toContainText('CATEGORY_CONFLICT');
    await expect(row(dialog, 'contacts').getByLabel(labels.english, { exact: true })).toHaveValue(proposal);
    assert.deepEqual((await cli('categories')).categories, external);
    await assert.rejects(() => invoke(main, 'save_categories', { categories: before.categories, expectedRevision: before.revision }), /CATEGORY_CONFLICT/);
    const invalid = external.map(category => category.id === customId ? { ...category, nameEn: 'Education' } : category);
    await assert.rejects(() => invoke(main, 'save_categories', { categories: invalid, expectedRevision: changed.revision }), /INVALID_CATEGORIES/);
    assert.equal((await cli('categories')).revision, changed.revision);
    await resize(920, 660);
    await expect(dialog.getByRole('button', { name: labels.save, exact: true })).toBeInViewport();
    await expect(dialog.getByRole('alert')).toBeInViewport();
    await main.screenshot({ path: path.join(runDirectory, `native-category-conflict-${locale}.png`) });
    await dialog.getByRole('button', { name: labels.cancel, exact: true }).click();
    await main.getByRole('button', { name: labels.discard, exact: true }).click();
    const fresh = await manager(locale);
    await expect(row(fresh, 'contacts').getByLabel(labels.english, { exact: true })).toHaveValue(`External people ${locale}`);
    await row(fresh, 'contacts').getByLabel(labels.english, { exact: true }).fill('People archive');
    await row(fresh, 'contacts').getByLabel(labels.chinese, { exact: true }).fill('人物档案');
    await save(fresh, locale);
    check(`Native ${locale} revision conflict preserves the draft; stale and invalid writes leave the catalog intact`);
  }
  await expect(nav('行程').locator('svg.lucide-plane')).toHaveCount(1);
  await expect(nav('人物档案').locator('svg.lucide-book-open')).toHaveCount(1);
  await expect(main.locator('.detail-category')).toHaveText('行程');
  dialog = await manager('zh');
  await row(dialog, customId).getByRole('button', { name: '选择图标', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '旅行', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(dialog.getByRole('button', { name: '新增分类', exact: true })).toBeInViewport();
  await expect(dialog.getByRole('button', { name: '保存更改', exact: true })).toBeInViewport();
  assert.equal(await main.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await main.screenshot({ path: path.join(runDirectory, 'native-categories-zh-compact.png') });
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await main.screenshot({ path: path.join(runDirectory, 'native-categories-sidebar-zh-compact.png') });
  await focusPreview();
  await expect(preview.getByRole('region', { name: '附件预览', exact: true })).toBeVisible();
  await expect(preview.getByRole('button', { name: /^(Close|关闭)$/ })).toHaveCount(0);
  await main.locator('.locale-toggle').click();
  dialog = await manager();
  await row(dialog, customId).getByRole('button', { name: 'Choose icon', exact: true }).click();
  await expect(dialog.getByRole('button', { name: 'Travel', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await main.screenshot({ path: path.join(runDirectory, 'native-categories-en-compact.png') });
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  check('Compact English and Chinese collection editors, sidebar labels and selected icons remain usable');
  await resize(1280, 820);
  await nav('People archive').click();
  await main.locator('.record-card').filter({ hasText: contact.title }).click();
  await focusPreview();
  await expect(preview.getByRole('region', { name: 'Attachment preview', exact: true })).toBeVisible();
  assert.deepEqual((await cli('categories')).categories, catalog.categories);
  assert.deepEqual((await cli('get', ['--id', recordId])).attachments, original.attachments);
}
